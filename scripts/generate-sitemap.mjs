#!/usr/bin/env node
// Emit the sitemap from locales.json, filtered to the locales active for this
// build, exactly as the router is.
//
// The output is written into the build directory, not into public/: it is a
// build product that depends on which locales this build shipped, and a copy
// committed under public/ would be served stale whenever that set changed.
//
// It runs as `postbuild`, not `prebuild`. React Router empties the build
// directory at the start of a build, so a sitemap written before it is simply
// deleted — with no error anywhere.
//
// `--stdout` prints instead of writing, for inspecting what a given locale set
// would publish without touching the build.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { REPO_ROOT } from './lib/site-content.mjs';
import { activeMatrix } from './lib/route-matrix.mjs';

const toStdout = process.argv.includes('--stdout');
const matrix = await activeMatrix();
const out = resolve(REPO_ROOT, 'build/client/sitemap.xml');
const multilingual = matrix.locales.length > 1;

const { origin, defaultLocale, locales, routes } = matrix;
const byCode = Object.fromEntries(locales.map(l => [l.code, l]));
const en = byCode[defaultLocale];

function pathFor(route, locale) {
  const prefix = route.localized ? locale.prefix : '';
  const segments = [prefix, route.path].filter(Boolean);
  return segments.length ? `/${segments.join('/')}/` : '/';
}

const entries = [];
for (const route of routes) {
  const targets = route.localized ? locales : [en];
  const alternates =
    route.localized && multilingual
      ? [
          ...locales.map(l => ({ hreflang: l.htmlLang, href: origin + pathFor(route, l) })),
          { hreflang: 'x-default', href: origin + pathFor(route, en) },
        ]
      : [];
  for (const locale of targets) {
    const lines = [`  <url>`, `    <loc>${origin}${pathFor(route, locale)}</loc>`];
    for (const alt of alternates) {
      lines.push(`    <xhtml:link rel="alternate" hreflang="${alt.hreflang}" href="${alt.href}"/>`);
    }
    lines.push(`    <priority>${route.priority}</priority>`, `  </url>`);
    entries.push(lines.join('\n'));
  }
}

const xml = [
  `<?xml version="1.0" encoding="UTF-8"?>`,
  `<!-- Generated by scripts/generate-sitemap.mjs from src/app/content/locales.json. Do not edit by hand. -->`,
  `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">`,
  ...entries,
  `</urlset>`,
  ``,
].join('\n');

if (toStdout) {
  process.stdout.write(xml);
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, xml);
  console.log(
    `sitemap: ${entries.length} URLs (${matrix.locales.map(l => l.code).join(', ')}) -> ${out}`,
  );
}
