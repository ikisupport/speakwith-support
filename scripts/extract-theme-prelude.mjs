#!/usr/bin/env node
// Inline the palette and the pre-paint script into a generated module.
//
// Both have to reach the browser inside the document <head>, before the
// deferred stylesheet loads and before any React code runs, or a dark-mode
// visitor gets a frame of the light palette. They are authored as a real
// stylesheet and a real script (src/theme-tokens.css, src/theme-prepaint.js)
// so they can be edited and linted as such, and inlined verbatim here.
// Generated and git-ignored; runs as pre{start,build}.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { REPO_ROOT } from './lib/site-content.mjs';

const tokensPath = resolve(REPO_ROOT, 'src/theme-tokens.css');
const prepaintPath = resolve(REPO_ROOT, 'src/theme-prepaint.js');

const tokens = readFileSync(tokensPath, 'utf8');
const prepaint = readFileSync(prepaintPath, 'utf8');

// Cheap shape checks, so a rename or a bad edit fails the build here rather
// than shipping a page with no palette and a silent light flash.
if (!tokens.includes('--bg:')) {
  throw new Error(`${tokensPath} defines no --bg token`);
}
if (!prepaint.includes('data-theme')) {
  throw new Error(`${prepaintPath} never sets data-theme`);
}

const out = resolve(REPO_ROOT, 'app/generated/theme-prelude.ts');
mkdirSync(resolve(REPO_ROOT, 'app/generated'), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/extract-theme-prelude.mjs from src/theme-tokens.css and
// src/theme-prepaint.js. Do not edit; git-ignored.

export const THEME_TOKENS_CSS = ${JSON.stringify(tokens)};

export const THEME_PREPAINT_JS = ${JSON.stringify(prepaint)};
`,
);
console.log(`theme prelude: ${tokens.length} B tokens + ${prepaint.length} B pre-paint script`);
