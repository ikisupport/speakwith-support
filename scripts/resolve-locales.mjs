#!/usr/bin/env node
// Write src/content/locales.active.ts: the locale matrix filtered to the
// locales active for this build, plus static imports of ONLY their copy files,
// so a disabled locale contributes no routes and no strings to the bundle.
// Generated and git-ignored; runs as pre{start,build}.
//
// The filtering itself is scripts/lib/active-locales.mjs, so every script and
// the build agree on which locales this build ships. Copy files are imported
// through the `@content` alias (vite.config.ts + tsconfig paths) because an
// import specifier cannot be computed from the environment.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { REPO_ROOT } from './lib/site-content.mjs';
import { activeMatrix } from './lib/route-matrix.mjs';

const matrix = await activeMatrix();
const out = resolve(REPO_ROOT, 'src/content/locales.active.ts');
const extra = matrix.locales.filter(l => l.code !== matrix.defaultLocale);

const imports = extra.map((l, i) => `import L${i} from '@content/copy.${l.code}.json';`).join('\n');
const entries = extra.map((l, i) => `  '${l.code}': L${i},`).join('\n');
const publicMatrix = {
  origin: matrix.origin,
  defaultLocale: matrix.defaultLocale,
  locales: matrix.locales.map(({ enabled, ...l }) => l),
  routes: matrix.routes,
};

const ts = `// GENERATED by scripts/resolve-locales.mjs from src/app/content/locales.json.
// Do not edit; git-ignored.
// Active locales for this build (${matrix.source}): ${matrix.locales.map(l => l.code).join(', ')}
${imports}

export const ACTIVE_MATRIX = ${JSON.stringify(publicMatrix, null, 2)} as const;

export const ACTIVE_TRANSLATIONS: Record<string, unknown> = {
${entries}
};
`;
writeFileSync(out, ts);
console.log(`locales: ${matrix.locales.map(l => l.code).join(', ')} (${matrix.source})`);
if (matrix.overridden) {
  console.log('locales: SPEAKWITH_LOCALES override is LOCAL ONLY; production ships the committed enabled flags');
}
